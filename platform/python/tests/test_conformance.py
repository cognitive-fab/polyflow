from polyflow_temporal.rules import PolicyError, check_admitted, policy_body, route_target  # noqa: E402


@pytest.mark.parametrize("case", load("routes.json")["admitted"], ids=lambda c: c["name"])
def test_an_admitted_policy_with_routes_digests_like_typescript(case):
    admitted = case["admitted"]
    assert digest(policy_body(admitted)) == admitted["digest"]
    check_admitted(admitted)
    raw = json.loads(case["raw"])
    assert ("routes" in admitted) == bool(raw.get("routes"))


@pytest.mark.parametrize("case", load("routes.json")["refused"], ids=lambda c: c["name"])
def test_a_route_typescript_refuses_is_refused(case):
    policy = {**load("routes.json")["admitted"][0]["admitted"], "routes": json.loads(case["raw"])["routes"]}
    policy["digest"] = digest(policy_body(policy))  # only the route is wrong
    with pytest.raises(PolicyError, match="routes"):
        check_admitted(policy)


def test_an_edited_admitted_policy_is_refused():
    policy = json.loads(json.dumps(load("routes.json")["admitted"][0]["admitted"]))
    policy["rules"] = []
    with pytest.raises(PolicyError, match="edited"):
        check_admitted(policy)


@pytest.mark.parametrize("case", load("routes.json")["target"], ids=lambda c: c["name"])
def test_route_target_matches_typescript(case):
    policy = {"routes": case["routes"]} if "routes" in case else load("routes.json")["policy"]
    assert route_target(policy, case["activityType"], json.loads(case["args"])) == case["target"]


